package Java.Arrar1Part2;

public class ArrayDefaultValues {
    public static void main(String[] args) {
        byte byt[] = new byte[5];
        short sh[] = new short[5];
        int arr[] = new int[5];
        
        float fl[] = new float[5];
        double doubl[] = new double[5];
        
        boolean boo[] = new boolean[5];
        char ch[] = new char[5];
        
        String str[] = new String[5];

        System.out.println("byte " + byt[0]);
        System.out.println("short " + sh[0]);
        System.out.println("int " + arr[0]);
        System.out.println("float " + fl[0]);
        System.out.println("double " + doubl[0]);
        System.out.println("boolean " + boo[0]);
        System.out.println("character " + ch[0]);
        System.out.println("string " + str[0]);
    }
}
